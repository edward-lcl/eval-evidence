def check_svg(brief: dict, render: dict, bd: str, rd: str) -> str:
    parts = head(brief, render, bd, rd)
    accent, teal = render["colors"]["accent"], render["colors"]["teal"]
    positions = ((70, 185), (570, 185), (1070, 185), (1070, 435), (570, 435), (70, 435))
    arrows = (((470, 300), (548, 300)), ((970, 300), (1048, 300)), ((1285, 402), (1285, 426)), ((1050, 550), (992, 550)), ((550, 550), (492, 550)))
    for idx, (gate, (x, y)) in enumerate(zip(render["gates"], positions)):
        color = accent if idx in (0, 3, 5) else teal
        parts.append(f'<rect x="{x}" y="{y}" width="430" height="198" rx="22" fill="{PANEL}" stroke="{color}" stroke-width="3"/>')
        parts.append(f'<circle cx="{x + 44}" cy="{y + 42}" r="24" fill="{color}"/>')
        label(parts, x + 44, y + 50, gate["number"], 22, BG, 700, "middle")
        gate_icon(parts, gate["icon"], x + 310, y + 24, color)
        label(parts, x + 30, y + 112, f'{gate["number"]}  {gate["title"]}', 23, INK, 700, spacing=1)
        label(parts, x + 30, y + 153, gate["detail"], 20, MUTED)
    for (x1, y1), (x2, y2) in arrows:
        parts.append(f'<path d="M{x1} {y1} L{x2} {y2}" stroke="#CBD5E1" stroke-width="5" marker-end="url(#arrow)"/>')
    # Report result branch placed inside the final card.
    parts.extend([
        f'<rect x="90" y="614" width="170" height="46" rx="23" fill="#102218" stroke="{render["colors"]["pass"]}" stroke-width="3"/>',
        f'<rect x="280" y="614" width="190" height="46" rx="23" fill="#261416" stroke="{render["colors"]["fail"]}" stroke-width="3"/>',
    ])
    label(parts, 175, 645, "PASS", 21, render["colors"]["pass"], 700, "middle")
    label(parts, 375, 645, "FAIL + REASON", 20, render["colors"]["fail"], 700, "middle")
    parts.extend([
        f'<rect x="70" y="705" width="715" height="145" rx="18" fill="#0E2116" stroke="{render["colors"]["pass"]}" stroke-width="3"/>',
        f'<rect x="815" y="705" width="715" height="145" rx="18" fill="#261416" stroke="{render["colors"]["fail"]}" stroke-width="3"/>',
    ])
    label(parts, 100, 743, "CHECKED NOW", 21, render["colors"]["pass"], 700, spacing=1)
    label(parts, 845, 743, "STILL NOT PROVEN", 21, render["colors"]["fail"], 700, spacing=1)
