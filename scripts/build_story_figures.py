def t(value: str) -> str:
    return escape(value, {'"': '&quot;'})


def head(brief: dict, render: dict, brief_digest: str, render_digest: str) -> list[str]:
    width, height = render["canvas"]["width"], render["canvas"]["height"]
    return [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<!-- generated by scripts/build_story_figures.py v{GENERATOR_VERSION}; brief-sha256={brief_digest}; render-sha256={render_digest} -->',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="figure-title figure-desc">',
        f'<title id="figure-title">{t(brief["title"])}</title>',
        f'<desc id="figure-desc">{t(brief["accessibility"]["long_description"])}</desc>',
        '<defs>',
        '<marker id="arrow" markerWidth="12" markerHeight="12" refX="10" refY="5" orient="auto"><path d="M0 0 L0 10 L11 5 Z" fill="#CBD5E1"/></marker>',
        '<filter id="glow" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="7" result="blur"/><feMerge><feMergeNode in="blur"/><feMergeNode in="SourceGraphic"/></feMerge></filter>',
        '</defs>',
        f'<rect width="{width}" height="{height}" fill="{BG}"/>',
        f'<text x="70" y="75" fill="{INK}" font-family="Arial, sans-serif" font-size="43" font-weight="700" letter-spacing="1">{t(brief["title"])}</text>',
        f'<text x="72" y="116" fill="{MUTED}" font-family="Arial, sans-serif" font-size="22">{t(render["subtitle"])}</text>',
    ]


def label(parts: list[str], x: int, y: int, value: str, size: int = 22, color: str = INK,
          weight: int = 400, anchor: str = "start", spacing: int = 0) -> None:
    parts.append(
        f'<text x="{x}" y="{y}" text-anchor="{anchor}" fill="{color}" font-family="Arial, sans-serif" '
        f'font-size="{size}" font-weight="{weight}" letter-spacing="{spacing}">{t(value)}</text>'
    )


