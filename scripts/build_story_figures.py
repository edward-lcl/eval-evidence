#!/usr/bin/env python3
"""Build the envelope, evidence-state, and mutation figures."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
FIGURES = ROOT / "figures"
FIGURE_IDS = (
    "eval-evidence-envelope-anatomy",
    "eval-evidence-evidence-states",
    "eval-evidence-tamper-story",
)
GENERATOR_VERSION = "2"
BG, PANEL, INK, MUTED = "#090E16", "#111827", "#F8FAFC", "#A7B0C0"


def t(value: object) -> str:
    return escape(str(value), {'"': '&quot;'})


def horizontal_arrow(x1: int, x2: int, y: int) -> list[str]:
    """Draw a connector with a separately visible shaft and head."""
    return [
        f'<line class="flow-arrow-body" x1="{x1}" y1="{y}" x2="{x2 - 16}" y2="{y}" stroke="#CBD5E1" stroke-width="5" stroke-linecap="round"/>',
        f'<path class="flow-arrow-head" d="M{x2 - 16} {y - 10} L{x2} {y} L{x2 - 16} {y + 10} Z" fill="#CBD5E1"/>',
    ]


def head(brief: dict, render: dict, bd: str, rd: str) -> list[str]:
    width, height = render["canvas"]["width"], render["canvas"]["height"]
    generator_version = "3" if render["figure_id"] == "eval-evidence-tamper-story" else GENERATOR_VERSION
    return [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<!-- generated by scripts/build_story_figures.py v{generator_version}; brief-sha256={bd}; render-sha256={rd} -->',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="figure-title figure-desc">',
        f'<title id="figure-title">{t(brief["title"])}</title>',
        f'<desc id="figure-desc">{t(brief["accessibility"]["long_description"])}</desc>',
        '<defs><marker id="arrow" markerWidth="11" markerHeight="11" refX="9" refY="5" orient="auto"><path d="M0 0 L0 10 L10 5 Z" fill="#CBD5E1"/></marker></defs>',
        f'<rect width="{width}" height="{height}" fill="{BG}"/>',
        f'<text x="70" y="80" fill="{INK}" font-family="Arial, sans-serif" font-size="44" font-weight="700">{t(brief["title"])}</text>',
        f'<text x="70" y="122" fill="{MUTED}" font-family="Arial, sans-serif" font-size="22">{t(render["subtitle"])}</text>',
    ]


def envelope_svg(brief: dict, render: dict, bd: str, rd: str) -> str:
    p = head(brief, render, bd, rd)
    p.extend([
        '<rect x="70" y="295" width="300" height="190" rx="24" fill="#111827" stroke="#FF7A59" stroke-width="4"/>',
        '<path d="M125 345 H190 L215 370 H315 V445 H125 Z" fill="#0B1220" stroke="#FF7A59" stroke-width="4"/>',
        f'<text x="220" y="525" text-anchor="middle" fill="#FF7A59" font-family="Arial, sans-serif" font-size="24" font-weight="700">{t(render["input"]["label"])}</text>',
        f'<text x="220" y="558" text-anchor="middle" fill="{MUTED}" font-family="Arial, sans-serif" font-size="20">{t(render["input"]["detail"])}</text>',
        '<path d="M390 390 H470" stroke="#CBD5E1" stroke-width="6" marker-end="url(#arrow)"/>',
        '<rect x="500" y="180" width="1030" height="500" rx="30" fill="#0B1220" stroke="#E2E8F0" stroke-width="4"/>',
        '<rect x="550" y="150" width="250" height="60" rx="30" fill="#E2E8F0"/>',
        f'<text x="675" y="190" text-anchor="middle" fill="{BG}" font-family="monospace" font-size="24" font-weight="700">evidence.json</text>',
    ])
    for section, y in zip(render["sections"], (245, 385, 525)):
        color = section["color"]
        p.extend([
            f'<rect x="550" y="{y}" width="930" height="110" rx="18" fill="{PANEL}" stroke="#334155" stroke-width="2"/>',
            f'<circle cx="600" cy="{y + 55}" r="25" fill="{color}"/>',
            f'<text x="600" y="{y + 64}" text-anchor="middle" fill="{BG}" font-family="Arial, sans-serif" font-size="22" font-weight="700">{t(section["number"])}</text>',
            f'<text x="650" y="{y + 46}" fill="{color}" font-family="Arial, sans-serif" font-size="23" font-weight="700">{t(section["title"])}</text>',
            f'<text x="650" y="{y + 80}" fill="{INK}" font-family="Arial, sans-serif" font-size="21">{t(section["detail"])}</text>',
        ])
    p.extend([
        '<rect x="550" y="720" width="930" height="64" rx="32" fill="#151A13" stroke="#F7D73A" stroke-width="3"/>',
        f'<text x="1015" y="761" text-anchor="middle" fill="#F7D73A" font-family="Arial, sans-serif" font-size="22" font-weight="700">{t(render["badge"])}</text>',
        '</svg>',
    ])
    return "\n".join(p) + "\n"


def states_svg(brief: dict, render: dict, bd: str, rd: str) -> str:
    p = head(brief, render, bd, rd)
    for group, y in zip(render["groups"], (175, 315, 455, 595)):
        color = group["color"]
        p.extend([
            f'<rect x="70" y="{y}" width="760" height="110" rx="20" fill="{PANEL}" stroke="#334155" stroke-width="2"/>',
            f'<circle cx="115" cy="{y + 55}" r="24" fill="{color}"/>',
            f'<text x="115" y="{y + 64}" text-anchor="middle" fill="{BG}" font-family="Arial, sans-serif" font-size="22" font-weight="700">{t(group["number"])}</text>',
            f'<text x="158" y="{y + 45}" fill="{color}" font-family="Arial, sans-serif" font-size="22" font-weight="700">{t(group["origin"])}</text>',
            f'<text x="158" y="{y + 78}" fill="{INK}" font-family="Arial, sans-serif" font-size="20">{t(group["detail"])}</text>',
            f'<path d="M850 {y + 55} H925" stroke="#CBD5E1" stroke-width="5" marker-end="url(#arrow)"/>',
        ])
        statuses = group["statuses"]
        if len(statuses) == 1:
            p.extend([
                f'<rect x="960" y="{y + 18}" width="570" height="74" rx="37" fill="#0B1220" stroke="{color}" stroke-width="4"/>',
                f'<text x="1245" y="{y + 65}" text-anchor="middle" fill="{color}" font-family="monospace" font-size="25" font-weight="700">{t(statuses[0])}</text>',
            ])
        else:
            for status, x in zip(statuses, (960, 1255)):
                p.extend([
                    f'<rect x="{x}" y="{y + 18}" width="275" height="74" rx="37" fill="#0B1220" stroke="{color}" stroke-width="4"/>',
                    f'<text x="{x + 137}" y="{y + 65}" text-anchor="middle" fill="{color}" font-family="monospace" font-size="21" font-weight="700">{t(status)}</text>',
                ])
    p.extend([
        '<line x1="70" y1="742" x2="1530" y2="742" stroke="#334155" stroke-width="2"/>',
        f'<text x="800" y="786" text-anchor="middle" fill="#F7D73A" font-family="Arial, sans-serif" font-size="21" font-weight="700" letter-spacing="2">{t(render["footer"])}</text>',
        '</svg>',
    ])
    return "\n".join(p) + "\n"


def tamper_svg(brief: dict, render: dict, bd: str, rd: str) -> str:
    p = head(brief, render, bd, rd)
    cards = [
        (render["before"], 70, "#20D66B"),
        (render["after"], 600, "#FF6F59"),
        (render["verify"], 1130, "#F7D73A"),
    ]
    for idx, (card, x, color) in enumerate(cards, 1):
        p.extend([
            f'<rect x="{x}" y="205" width="400" height="310" rx="24" fill="{PANEL}" stroke="{color}" stroke-width="4"/>',
            f'<circle cx="{x + 44}" cy="249" r="23" fill="{color}"/>',
            f'<text x="{x + 44}" y="258" text-anchor="middle" fill="{BG}" font-family="Arial, sans-serif" font-size="22" font-weight="700">{idx}</text>',
            f'<text x="{x + 86}" y="258" fill="{color}" font-family="Arial, sans-serif" font-size="25" font-weight="700">{t(card["verb"])}</text>',
        ])
        if idx < 3:
            p.extend([
                f'<text x="{x + 38}" y="332" fill="{INK}" font-family="monospace" font-size="24" font-weight="700">{t(card["file"])}</text>',
                f'<text x="{x + 38}" y="380" fill="{INK}" font-family="monospace" font-size="24">{t(card["value"])}</text>',
                f'<text x="{x + 38}" y="453" fill="{MUTED}" font-family="Arial, sans-serif" font-size="20">SHA-256</text>',
                f'<text x="{x + 160}" y="453" fill="{color}" font-family="monospace" font-size="25" font-weight="700">{t(card["digest"])}</text>',
                *horizontal_arrow(x + 418, cards[idx][1] - 20, 360),
            ])
        else:
            p.extend([
                f'<text x="{x + 38}" y="330" fill="{MUTED}" font-family="Arial, sans-serif" font-size="20">EXPECTED</text>',
                f'<text x="{x + 175}" y="330" fill="{INK}" font-family="monospace" font-size="24" font-weight="700">{t(card["expected"])}</text>',
                f'<text x="{x + 38}" y="385" fill="{MUTED}" font-family="Arial, sans-serif" font-size="20">ACTUAL</text>',
                f'<text x="{x + 175}" y="385" fill="#FF6F59" font-family="monospace" font-size="24" font-weight="700">{t(card["actual"])}</text>',
                f'<text x="{x + 200}" y="447" text-anchor="middle" fill="#FF6F59" font-family="Arial, sans-serif" font-size="27" font-weight="700">≠</text>',
                f'<text x="{x + 200}" y="487" text-anchor="middle" fill="#FF6F59" font-family="Arial, sans-serif" font-size="22" font-weight="700">{t(card["result"])}</text>',
            ])
    p.extend([
        '<rect x="245" y="580" width="1110" height="86" rx="18" fill="#261416" stroke="#FF6F59" stroke-width="3"/>',
        f'<text x="800" y="632" text-anchor="middle" fill="{INK}" font-family="monospace" font-size="23" font-weight="700">{t(render["error"])}</text>',
        '</svg>',
    ])
    return "\n".join(p) + "\n"


BUILDERS = {
    "eval-evidence-envelope-anatomy": envelope_svg,
    "eval-evidence-evidence-states": states_svg,
    "eval-evidence-tamper-story": tamper_svg,
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale: list[str] = []
    for figure_id in FIGURE_IDS:
        bp, rp = FIGURES / f"{figure_id}.figure.json", FIGURES / f"{figure_id}.render.json"
        bb, rb = bp.read_text(encoding="utf-8").encode("utf-8"), rp.read_text(encoding="utf-8").encode("utf-8")
        built = BUILDERS[figure_id](json.loads(bb), json.loads(rb), hashlib.sha256(bb).hexdigest(), hashlib.sha256(rb).hexdigest())
        output = FIGURES / f"{figure_id}.svg"
        if args.check:
            if not output.exists() or output.read_text(encoding="utf-8") != built:
                stale.append(output.name)
        else:
            output.write_text(built, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("canonical story SVGs are stale: " + ", ".join(stale))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
