BUILDERS = {
    "eval-evidence-envelope-anatomy": envelope_svg,
    "eval-evidence-check-story": check_svg,
    "eval-evidence-tamper-story": tamper_svg,
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if any canonical story SVG is stale")
    args = parser.parse_args()
    stale = []
    for figure_id in FIGURE_IDS:
        brief_path = FIGURES / f"{figure_id}.figure.json"
        render_path = FIGURES / f"{figure_id}.render.json"
        output = FIGURES / f"{figure_id}.svg"
        brief_bytes = brief_path.read_text(encoding="utf-8").encode("utf-8")
        render_bytes = render_path.read_text(encoding="utf-8").encode("utf-8")
        rendered = BUILDERS[figure_id](
            json.loads(brief_bytes),
            json.loads(render_bytes),
            hashlib.sha256(brief_bytes).hexdigest(),
            hashlib.sha256(render_bytes).hexdigest(),
        )
        if args.check:
            if not output.exists() or output.read_text(encoding="utf-8") != rendered:
                stale.append(output.name)
        else:
            output.write_text(rendered, encoding="utf-8")
    if stale:
        raise SystemExit("canonical story SVGs are stale: " + ", ".join(stale))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
