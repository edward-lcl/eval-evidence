def check_story(brief: dict, render: dict) -> str:
    p: list[str] = []
    header(p, brief, render, "scripts/build_mobile_figures.py v1")
    for i, gate in enumerate(render["gates"]):
        x = 52
        y = 185 + i * 127
        p += [box(x, y, 796, 108, TEAL), text(x + 25, y + 39, f'{gate["number"]}  {gate["title"]}', 25, WHITE, 800),
              text(x + 25, y + 79, gate["detail"], 22, MUTED, 500)]
    p += [box(52, 980, 388, 150, GREEN), text(82, 1035, "PASS", 33, GREEN, 800),
          text(82, 1085, "all requested tests passed", 24, WHITE, 500),
          box(460, 980, 388, 150, RED), text(490, 1035, "FAIL + REASON", 31, RED, 800),
          text(490, 1085, "the failing gate is named", 24, WHITE, 500),
          box(52, 1175, 796, 170, TEAL), text(82, 1222, "CHECKED NOW", 28, TEAL, 800)]
    for i, value in enumerate(render["checked"]):
        x = 82 if i % 2 == 0 else 460
        y = 1263 if i < 2 else 1305
        p.append(text(x, y, "• " + value, 23, WHITE, 500))
    p += [box(52, 1375, 796, 160, YELLOW), text(82, 1422, "STILL NOT PROVEN", 28, YELLOW, 800)]
    for i, value in enumerate(render["not_proven"]):
        p.append(text(82, 1462 + i * 31, "• " + value, 23, WHITE, 500))
    p.append("</svg>")
    return "\n".join(p) + "\n"


def tamper(brief: dict, render: dict) -> str:
    p: list[str] = []
    header(p, brief, render, "scripts/build_mobile_figures.py v1")
    stages = [
        ("1  SAVE THE BASELINE", "result.json", "SAVED SHA-256", TEAL),
        ("2  THE FILE CHANGES", "result.json", "one byte is now different", CORAL),
        ("3  VERIFY LATER BYTES", "EXPECTED  a91f…", "ACTUAL       7c42…", YELLOW),
    ]
    for i, (title, first, second, color) in enumerate(stages):
        y = 195 + i * 330
        p += [box(52, y, 796, 270, color), text(82, y + 53, title, 31, color, 800),
              box(82, y + 82, 736, 125, "#475569", "#0C1722", 16, 2),
              text(112, y + 133, first, 29, WHITE, 700), text(112, y + 178, second, 26, MUTED, 500)]
        if i < 2:
            p += [line(450, y + 270, 450, y + 318, color, 5), text(450, y + 307, "▼", 28, color, 800, "middle")]
    p += [box(52, 1205, 796, 145, RED), text(450, 1260, "MISMATCH · EXIT 1", 34, RED, 800, "middle"),
          text(450, 1310, "Referenced file digest mismatch for result.json", 25, WHITE, 600, "middle"),
          box(52, 1400, 796, 110, GREEN), text(450, 1468, "STORE THE BUNDLE SEPARATELY", 30, GREEN, 800, "middle"), "</svg>"]
    return "\n".join(p) + "\n"


BUILDERS = {
    "eval-evidence-lifecycle": lifecycle,
    "eval-evidence-command-path": command,
    "eval-evidence-envelope-anatomy": envelope,
    "eval-evidence-check-story": check_story,
    "eval-evidence-tamper-story": tamper,
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale: list[str] = []
    for figure_id in IDS:
        brief = json.loads((FIGURES / f"{figure_id}.figure.json").read_text(encoding="utf-8"))
        render = json.loads((FIGURES / f"{figure_id}.render.json").read_text(encoding="utf-8"))
        output = FIGURES / f"{figure_id}-mobile.svg"
        built = BUILDERS[figure_id](brief, render)
        if args.check:
            if not output.exists() or output.read_text(encoding="utf-8") != built:
                stale.append(output.name)
        else:
            output.write_text(built, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("stale mobile SVGs: " + ", ".join(stale))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
