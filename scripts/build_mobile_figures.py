#!/usr/bin/env python3
"""Build phone-first figures from the same semantic and render inputs as desktop."""
from __future__ import annotations

import argparse
import hashlib
import html
import json
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIGURES = ROOT / "figures"
IDS = (
    "eval-evidence-lifecycle",
    "eval-evidence-command-path",
    "eval-evidence-envelope-anatomy",
    "eval-evidence-evidence-states",
    "eval-evidence-tamper-story",
)
VERSION = "2"
BG, PANEL, INK, MUTED = "#090E16", "#111827", "#F8FAFC", "#A7B0C0"


def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def txt(x: int, y: int, value: object, size: int = 24, color: str = INK,
        weight: int = 500, anchor: str = "start", family: str = "Arial") -> str:
    return f'<text x="{x}" y="{y}" text-anchor="{anchor}" fill="{color}" font-family="{family}" font-size="{size}" font-weight="{weight}">{esc(value)}</text>'


def box(x: int, y: int, width: int, height: int, stroke: str = "#334155",
        fill: str = PANEL, radius: int = 22, stroke_width: int = 3) -> str:
    return f'<rect x="{x}" y="{y}" width="{width}" height="{height}" rx="{radius}" fill="{fill}" stroke="{stroke}" stroke-width="{stroke_width}"/>'


def header(parts: list[str], brief: dict, render: dict) -> int:
    canvas = render["mobile_canvas"]
    bp = FIGURES / f'{render["figure_id"]}.figure.json'
    rp = FIGURES / f'{render["figure_id"]}.render.json'
    bd = hashlib.sha256(bp.read_text(encoding="utf-8").encode("utf-8")).hexdigest()
    rd = hashlib.sha256(rp.read_text(encoding="utf-8").encode("utf-8")).hexdigest()
    parts.extend([
        f'<!-- generated by scripts/build_mobile_figures.py v{VERSION}; mobile=true; brief-sha256={bd}; render-sha256={rd} -->',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{canvas["width"]}" height="{canvas["height"]}" viewBox="0 0 {canvas["width"]} {canvas["height"]}" role="img" aria-labelledby="figure-title figure-desc">',
        f'<title id="figure-title">{esc(brief["title"])}</title>',
        f'<desc id="figure-desc">{esc(brief["accessibility"]["long_description"])}</desc>',
        '<defs><marker id="arrow" markerWidth="11" markerHeight="11" refX="9" refY="5" orient="auto"><path d="M0 0 L0 10 L10 5 Z" fill="#CBD5E1"/></marker></defs>',
        f'<rect width="{canvas["width"]}" height="{canvas["height"]}" fill="{BG}"/>',
    ])
    y = 54
    for value in textwrap.wrap(brief["title"], width=35):
        parts.append(txt(50, y, value, 31, INK, 800)); y += 38
    y += 12
    for value in textwrap.wrap(brief["takeaway"], width=58):
        parts.append(txt(50, y, value, 21, MUTED, 500)); y += 28
    return y + 24


def lifecycle(brief: dict, render: dict) -> str:
    p: list[str] = []
    y = header(p, brief, render)
    for i, stage in enumerate(render["stages"]):
        color = stage["color"]
        p.extend([
            box(50, y, 800, 128, color),
            f'<circle cx="92" cy="{y + 42}" r="22" fill="{color}"/>',
            txt(92, y + 50, stage["number"], 21, BG, 800, "middle"),
            txt(132, y + 50, stage["label"], 27, color, 800),
            txt(82, y + 91, stage["detail"], 23, INK, 500),
        ])
        if stage.get("note"):
            p.append(txt(540, y + 91, stage["note"], 20, MUTED, 500))
        y += 156
        if i < 3:
            p.append(f'<path d="M450 {y - 28} V{y - 8}" stroke="#CBD5E1" stroke-width="5" marker-end="url(#arrow)"/>')
    p.extend([
        box(190, y - 2, 520, 62, "#F7D73A", "#151A13", 31),
        txt(450, y + 38, render["output"], 22, "#F7D73A", 800, "middle"),
        txt(450, y + 91, "records + checks evidence", 21, INK, 700, "middle"),
        txt(450, y + 120, "does not run, compare, or adjudicate", 20, MUTED, 500, "middle"),
        '</svg>',
    ])
    return "\n".join(p) + "\n"


def command(brief: dict, render: dict) -> str:
    p: list[str] = []
    y = header(p, brief, render)
    for lane in render["lanes"]:
        color = lane["color"]
        height = 300 if len(lane["steps"]) == 1 else 390
        p.extend([box(50, y, 800, height, color), txt(80, y + 48, lane["label"], 28, color, 800)])
        prompt_y = y + 84
        for value in textwrap.wrap(lane["prompt"], width=50):
            p.append(txt(80, prompt_y, value, 21, MUTED, 500)); prompt_y += 27
        step_y = y + 125
        for step in lane["steps"]:
            p.extend([
                box(80, step_y, 740, 66, color, "#0B1220", 15),
                txt(450, step_y + 42, step, 22, INK, 700, "middle", "monospace"),
            ])
            step_y += 88
            if step_y < y + height - 85:
                p.append(f'<path d="M450 {step_y - 18} V{step_y - 5}" stroke="#CBD5E1" stroke-width="4" marker-end="url(#arrow)"/>')
        p.extend([
            txt(80, y + height - 53, lane["note"], 20, color, 800),
            txt(820, y + height - 53, lane["result"], 21, color, 800, "end"),
        ])
        y += height + 34
    p.append('</svg>')
    return "\n".join(p) + "\n"


def envelope(brief: dict, render: dict) -> str:
    p: list[str] = []
    y = header(p, brief, render)
    p.extend([
        box(240, y, 420, 88, "#FF7A59"),
        txt(450, y + 38, render["input"]["label"], 26, "#FF7A59", 800, "middle"),
        txt(450, y + 68, render["input"]["detail"], 21, MUTED, 500, "middle"),
        f'<path d="M450 {y + 94} V{y + 130}" stroke="#CBD5E1" stroke-width="5" marker-end="url(#arrow)"/>',
    ])
    y += 148
    p.extend([box(50, y, 800, 660, "#E2E8F0", "#0B1220", 28, 4), txt(450, y + 55, "evidence.json", 27, INK, 800, "middle", "monospace")])
    section_y = y + 90
    for section in render["sections"]:
        color = section["color"]
        p.extend([
            box(82, section_y, 736, 145, color),
            f'<circle cx="126" cy="{section_y + 43}" r="22" fill="{color}"/>',
            txt(126, section_y + 51, section["number"], 21, BG, 800, "middle"),
            txt(165, section_y + 51, section["title"], 23, color, 800),
            txt(112, section_y + 101, section["detail"], 21, INK, 500),
        ])
        section_y += 172
    p.extend([
        box(120, y + 610, 660, 64, "#F7D73A", "#151A13", 32),
        txt(450, y + 651, render["badge"], 22, "#F7D73A", 800, "middle"),
        '</svg>',
    ])
    return "\n".join(p) + "\n"


def states(brief: dict, render: dict) -> str:
    p: list[str] = []
    y = header(p, brief, render)
    for group in render["groups"]:
        color = group["color"]
        height = 200 if len(group["statuses"]) == 1 else 260
        p.extend([
            box(50, y, 800, height, color),
            f'<circle cx="92" cy="{y + 42}" r="22" fill="{color}"/>',
            txt(92, y + 50, group["number"], 21, BG, 800, "middle"),
            txt(132, y + 50, group["origin"], 23, color, 800),
            txt(82, y + 88, group["detail"], 20, MUTED, 500),
        ])
        status_y = y + 116
        for status in group["statuses"]:
            p.extend([box(82, status_y, 736, 60, color, "#0B1220", 30), txt(450, status_y + 39, status, 23, color, 800, "middle", "monospace")])
            status_y += 72
        y += height + 24
    p.extend([txt(450, y + 20, render["footer"], 20, "#F7D73A", 800, "middle"), '</svg>'])
    return "\n".join(p) + "\n"


def tamper(brief: dict, render: dict) -> str:
    p: list[str] = []
    y = header(p, brief, render)
    cards = [(render["before"], "#20D66B"), (render["after"], "#FF6F59"), (render["verify"], "#F7D73A")]
    for idx, (card, color) in enumerate(cards, 1):
        height = 190 if idx < 3 else 235
        p.extend([
            box(50, y, 800, height, color),
            f'<circle cx="92" cy="{y + 42}" r="22" fill="{color}"/>',
            txt(92, y + 50, idx, 21, BG, 800, "middle"),
            txt(132, y + 50, card["verb"], 27, color, 800),
        ])
        if idx < 3:
            p.extend([
                txt(82, y + 98, card["file"], 22, INK, 700, family="monospace"),
                txt(340, y + 98, card["value"], 22, INK, 500, family="monospace"),
                txt(82, y + 148, "SHA-256", 20, MUTED, 500),
                txt(220, y + 148, card["digest"], 24, color, 800, family="monospace"),
            ])
        else:
            p.extend([
                txt(82, y + 100, "EXPECTED", 20, MUTED, 500), txt(270, y + 100, card["expected"], 23, INK, 800, family="monospace"),
                txt(82, y + 145, "ACTUAL", 20, MUTED, 500), txt(270, y + 145, card["actual"], 23, "#FF6F59", 800, family="monospace"),
                txt(790, y + 126, "≠", 31, "#FF6F59", 800, "end"),
                txt(450, y + 198, card["result"], 23, "#FF6F59", 800, "middle"),
            ])
        y += height + 28
        if idx < 3:
            p.append(f'<path d="M450 {y - 28} V{y - 8}" stroke="#CBD5E1" stroke-width="5" marker-end="url(#arrow)"/>')
    p.extend([
        box(50, y, 800, 84, "#FF6F59", "#261416", 18),
        txt(450, y + 51, render["error"], 20, INK, 700, "middle", "monospace"),
        '</svg>',
    ])
    return "\n".join(p) + "\n"


BUILDERS = {
    "eval-evidence-lifecycle": lifecycle,
    "eval-evidence-command-path": command,
    "eval-evidence-envelope-anatomy": envelope,
    "eval-evidence-evidence-states": states,
    "eval-evidence-tamper-story": tamper,
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale: list[str] = []
    for figure_id in IDS:
        brief = json.loads((FIGURES / f"{figure_id}.figure.json").read_text(encoding="utf-8"))
        render = json.loads((FIGURES / f"{figure_id}.render.json").read_text(encoding="utf-8"))
        built = BUILDERS[figure_id](brief, render)
        output = FIGURES / f"{figure_id}-mobile.svg"
        if args.check:
            if not output.exists() or output.read_text(encoding="utf-8") != built:
                stale.append(output.name)
        else:
            output.write_text(built, encoding="utf-8", newline="\n")
    if stale:
        raise SystemExit("stale mobile SVGs: " + ", ".join(stale))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
