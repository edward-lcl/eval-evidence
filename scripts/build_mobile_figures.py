#!/usr/bin/env python3
"""Build portrait story panels from the canonical figure briefs and render manifests."""
from __future__ import annotations

import argparse
import hashlib
import html
import json
import textwrap
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FIGURES = ROOT / "figures"
IDS = (
    "eval-evidence-lifecycle",
    "eval-evidence-command-path",
    "eval-evidence-envelope-anatomy",
    "eval-evidence-check-story",
    "eval-evidence-tamper-story",
)
WIDTH, HEIGHT = 900, 1600
BG, PANEL, WHITE, MUTED = "#090E16", "#111827", "#F8FAFC", "#A9B4C5"
YELLOW, TEAL, CORAL, GREEN, RED = "#F7D73A", "#39D0C3", "#FF7A59", "#20D66B", "#FF5C5C"


def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def text(x: int, y: int, value: object, size: int = 36, color: str = WHITE,
         weight: int = 600, anchor: str = "start", family: str = "Arial") -> str:
    return (f'<text x="{x}" y="{y}" fill="{color}" font-family="{family}" '
            f'font-size="{size}" font-weight="{weight}" text-anchor="{anchor}">{esc(value)}</text>')


def box(x: int, y: int, width: int, height: int, stroke: str = "#334155",
        fill: str = PANEL, radius: int = 24, stroke_width: int = 3) -> str:
    return (f'<rect x="{x}" y="{y}" width="{width}" height="{height}" rx="{radius}" '
            f'fill="{fill}" stroke="{stroke}" stroke-width="{stroke_width}"/>')


def line(x1: int, y1: int, x2: int, y2: int, color: str = MUTED,
         width: int = 4, dash: str | None = None) -> str:
    extra = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<path d="M{x1} {y1} L{x2} {y2}" stroke="{color}" stroke-width="{width}" fill="none"{extra}/>'


def header(parts: list[str], brief: dict, render: dict, generator: str, show_takeaway: bool = True) -> None:
    # Normalize checkout line endings before hashing, as the wide builders do.
    brief_path = FIGURES / f'{render["figure_id"]}.figure.json'
    render_path = FIGURES / f'{render["figure_id"]}.render.json'
    brief_digest = hashlib.sha256(brief_path.read_text(encoding="utf-8").encode("utf-8")).hexdigest()
    render_digest = hashlib.sha256(render_path.read_text(encoding="utf-8").encode("utf-8")).hexdigest()
    parts.extend([
        f'<!-- generated by {generator}; mobile=true; brief-sha256={brief_digest}; render-sha256={render_digest} -->',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}" role="img" aria-labelledby="figure-title figure-desc">',
        f'<title id="figure-title">{esc(brief["title"])}</title>',
        f'<desc id="figure-desc">{esc(brief["accessibility"]["long_description"])}</desc>',
        f'<rect width="{WIDTH}" height="{HEIGHT}" fill="{BG}"/>',
    ])
    title_lines = textwrap.wrap(brief["title"], width=38)[:2]
    takeaway_lines = textwrap.wrap(brief["takeaway"], width=62)[:2] if show_takeaway else []
    for index, value in enumerate(title_lines):
        parts.append(text(52, 55 + index * 39, value, 32, WHITE, 800))
    for index, value in enumerate(takeaway_lines):
        parts.append(text(52, 132 + index * 29, value, 23, MUTED, 500))


def lifecycle(brief: dict, render: dict) -> str:
    p: list[str] = []
    header(p, brief, render, "scripts/build_mobile_figures.py v1")
    y_positions = [180, 405, 630]
    for index, (stage, y) in enumerate(zip(render["stages"], y_positions), 1):
        p += [box(52, y, 796, 180, stage["color"]), text(82, y + 49, f"{index}", 32, stage["color"], 800),
              text(135, y + 49, stage["label"], 37, WHITE, 800)]
        for row, detail in enumerate(stage["detail_lines"]):
            p.append(text(82, y + 97 + row * 34, detail, 28, MUTED, 500))
        if index < 3:
            p += [line(450, y + 180, 450, y + 217, stage["color"], 5),
                  text(450, y + 211, "▼", 28, stage["color"], 800, "middle")]
    chips = ["model", "harness", "budgets", "verifier", "artifacts", "field provenance"]
    for i, label in enumerate(chips):
        x = 52 if i % 2 == 0 else 460
        y = 832 + (i // 2) * 62
        p += [box(x, y, 388, 50, TEAL, "#0C1722", 25, 2), text(x + 194, y + 35, label, 24, WHITE, 700, "middle")]
    p.append(text(52, 1044, "REVIEW OUTCOME", 28, YELLOW, 800))
    for i, outcome in enumerate(render["outcomes"]):
        x = 52 if i % 2 == 0 else 460
        y = 1068 if i < 2 else 1233
        label_size = 23 if len(outcome["label"]) > 16 else 27
        p += [box(x, y, 388, 140, outcome["color"]),
              text(x + 24, y + 43, outcome["label"], label_size, outcome["color"], 800)]
        for row, detail in enumerate(outcome["detail_lines"]):
            p.append(text(x + 24, y + 86 + row * 29, detail, 22, WHITE, 500))
    p += [line(52, 1418, 848, 1418, YELLOW, 3), text(52, 1462, "BOUNDARY", 26, YELLOW, 800),
          text(52, 1502, "records evidence — it does not prove the score", 25, WHITE, 600), "</svg>"]
    return "\n".join(p) + "\n"


def command(brief: dict, render: dict) -> str:
    p: list[str] = []
    header(p, brief, render, "scripts/build_mobile_figures.py v1", show_takeaway=False)
    p += [text(52, 133, "COMMAND", 23, YELLOW, 800), text(265, 133, "YOUR NEXT MOVE", 23, YELLOW, 800),
          text(620, 133, "VISIBLE RESULT", 23, YELLOW, 800), text(52, 1518, "PROOF BOUNDARY", 24, YELLOW, 800)]
    for index, item in enumerate(render["commands"]):
        y = 160 + index * 305
        p += [box(52, y, 796, 270, item["color"]), text(82, y + 43, item["step"], 25, item["color"], 800),
              text(82, y + 88, item["command"], 29 if len(item["command"]) > 9 else 38, WHITE, 800)]
        for row, value in enumerate(item["action_lines"]):
            p.append(text(305, y + 48 + row * 31, value, 23, WHITE, 600))
        for row, value in enumerate(item["output_lines"]):
            p.append(text(735, y + 48 + row * 31, value, 22, item["color"], 800, "middle"))
        p += [line(82, y + 117, 818, y + 117, "#334155", 2), text(82, y + 161, "PROVES", 22, GREEN, 800),
              text(205, y + 161, item["proof"], 24, WHITE, 600), text(82, y + 211, "DOES NOT PROVE", 22, RED, 800),
              text(310, y + 211, item["limit"], 24, WHITE, 600)]
    p += [text(52, 1458, "KEEP THE BOUNDARY VISIBLE", 29, YELLOW, 800), "</svg>"]
    return "\n".join(p) + "\n"


