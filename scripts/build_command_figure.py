#!/usr/bin/env python3
"""Build the report-now versus saved-baseline command figure."""
from __future__ import annotations

import argparse
import hashlib
import json
import textwrap
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
FIGURES = ROOT / "figures"
FIGURE_ID = "eval-evidence-command-path"
GENERATOR_VERSION = "3"
BG, PANEL, INK, MUTED = "#090E16", "#111827", "#F8FAFC", "#A7B0C0"


def t(value: object) -> str:
    return escape(str(value), {'"': '&quot;'})


def svg(brief: dict, render: dict, bd: str, rd: str) -> str:
    width, height = render["canvas"]["width"], render["canvas"]["height"]
    p = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<!-- generated by scripts/build_command_figure.py v{GENERATOR_VERSION}; brief-sha256={bd}; render-sha256={rd} -->',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="figure-title figure-desc">',
        f'<title id="figure-title">{t(brief["title"])}</title>',
        f'<desc id="figure-desc">{t(brief["accessibility"]["long_description"])}</desc>',
        '<defs><marker id="arrow" markerWidth="11" markerHeight="11" refX="9" refY="5" orient="auto"><path d="M0 0 L0 10 L10 5 Z" fill="#CBD5E1"/></marker></defs>',
        f'<rect width="{width}" height="{height}" fill="{BG}"/>',
        f'<text x="70" y="80" fill="{INK}" font-family="Arial, sans-serif" font-size="44" font-weight="700">{t(brief["title"])}</text>',
        f'<text x="70" y="122" fill="{MUTED}" font-family="Arial, sans-serif" font-size="23">{t(render["subtitle"])}</text>',
    ]
    for lane, y in zip(render["lanes"], (205, 465)):
        color = lane["color"]
        prompt = lane["prompt"]
        prompt_lines = textwrap.wrap(prompt, width=20)
        p.extend([
            f'<rect x="70" y="{y}" width="1460" height="205" rx="24" fill="{PANEL}" stroke="#334155" stroke-width="3"/>',
            f'<rect x="70" y="{y}" width="250" height="205" rx="24" fill="#0B1220" stroke="{color}" stroke-width="4"/>',
            f'<text x="195" y="{y + 68}" text-anchor="middle" fill="{color}" font-family="Arial, sans-serif" font-size="25" font-weight="700">{t(lane["label"])}</text>',
        ])
        for i, prompt_line in enumerate(prompt_lines):
            p.append(f'<text x="195" y="{y + 113 + i * 28}" text-anchor="middle" fill="{INK}" font-family="Arial, sans-serif" font-size="20">{t(prompt_line)}</text>')
        step_xs = [380] if len(lane["steps"]) == 1 else [350, 735]
        step_widths = [510] if len(lane["steps"]) == 1 else [340, 520]
        for idx, (step, x, step_width) in enumerate(zip(lane["steps"], step_xs, step_widths)):
            p.extend([
                f'<rect x="{x}" y="{y + 50}" width="{step_width}" height="82" rx="16" fill="#0B1220" stroke="{color}" stroke-width="3"/>',
                f'<text x="{x + step_width / 2}" y="{y + 101}" text-anchor="middle" fill="{INK}" font-family="monospace" font-size="{20 if len(step) > 20 else 22}" font-weight="700">{t(step)}</text>',
            ])
            if idx < len(lane["steps"]) - 1:
                p.append(f'<path d="M{x + step_width + 10} {y + 91} H{x + step_width + 54}" stroke="#CBD5E1" stroke-width="5" marker-end="url(#arrow)"/>')
        result_x = 1285 if len(lane["steps"]) == 2 else 1110
        prior_end = step_xs[-1] + step_widths[-1]
        p.extend([
            f'<path d="M{prior_end + 10} {y + 91} H{result_x - 24}" stroke="#CBD5E1" stroke-width="5" marker-end="url(#arrow)"/>',
            f'<rect x="{result_x}" y="{y + 42}" width="{210 if len(lane["steps"]) == 2 else 235}" height="98" rx="49" fill="#151A13" stroke="{color}" stroke-width="4"/>',
            f'<text x="{result_x + (105 if len(lane["steps"]) == 2 else 117)}" y="{y + 101}" text-anchor="middle" fill="{color}" font-family="Arial, sans-serif" font-size="{20 if len(lane["result"]) > 16 else 21}" font-weight="700">{t(lane["result"])}</text>',
            f'<text x="380" y="{y + 177}" fill="{color}" font-family="Arial, sans-serif" font-size="20" font-weight="700">{t(lane["note"])}</text>',
        ])
    p.append('</svg>')
    return "\n".join(p) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    bp, rp = FIGURES / f"{FIGURE_ID}.figure.json", FIGURES / f"{FIGURE_ID}.render.json"
    bb, rb = bp.read_text(encoding="utf-8").encode("utf-8"), rp.read_text(encoding="utf-8").encode("utf-8")
    built = svg(json.loads(bb), json.loads(rb), hashlib.sha256(bb).hexdigest(), hashlib.sha256(rb).hexdigest())
    output = FIGURES / f"{FIGURE_ID}.svg"
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != built:
            raise SystemExit("canonical command SVG is stale; run scripts/build_command_figure.py")
    else:
        output.write_text(built, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
