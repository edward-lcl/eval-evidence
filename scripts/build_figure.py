#!/usr/bin/env python3
"""Build the current Eval Evidence pipeline figure."""
from __future__ import annotations

import argparse
import hashlib
import json
import textwrap
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
FIGURES = ROOT / "figures"
FIGURE_ID = "eval-evidence-lifecycle"
GENERATOR_VERSION = "4"
BG, PANEL, INK, MUTED = "#090E16", "#111827", "#F8FAFC", "#A7B0C0"


def t(value: object) -> str:
    return escape(str(value), {'"': '&quot;'})


def svg(brief: dict, render: dict, brief_digest: str, render_digest: str) -> str:
    width, height = render["canvas"]["width"], render["canvas"]["height"]
    parts = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        f'<!-- generated by scripts/build_figure.py v{GENERATOR_VERSION}; brief-sha256={brief_digest}; render-sha256={render_digest} -->',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="figure-title figure-desc">',
        f'<title id="figure-title">{t(brief["title"])}</title>',
        f'<desc id="figure-desc">{t(brief["accessibility"]["long_description"])}</desc>',
        '<defs><marker id="arrow" markerWidth="11" markerHeight="11" refX="9" refY="5" orient="auto"><path d="M0 0 L0 10 L10 5 Z" fill="#CBD5E1"/></marker></defs>',
        f'<rect width="{width}" height="{height}" fill="{BG}"/>',
        f'<text x="70" y="80" fill="{INK}" font-family="Arial, sans-serif" font-size="44" font-weight="700">{t(brief["title"])}</text>',
        f'<text x="70" y="122" fill="{MUTED}" font-family="Arial, sans-serif" font-size="23">{t(render["subtitle"])}</text>',
        '<text x="1530" y="80" text-anchor="end" fill="#39D0C3" font-family="Arial, sans-serif" font-size="20" font-weight="700" letter-spacing="2">SHIPPED PATH</text>',
    ]
    xs = [70, 435, 800, 1165]
    for index, (stage, x) in enumerate(zip(render["stages"], xs)):
        color = stage["color"]
        parts.extend([
            f'<rect x="{x}" y="230" width="310" height="230" rx="22" fill="{PANEL}" stroke="{color}" stroke-width="4"/>',
            f'<circle cx="{x + 42}" cy="272" r="22" fill="{color}"/>',
            f'<text x="{x + 42}" y="280" text-anchor="middle" fill="{BG}" font-family="Arial, sans-serif" font-size="21" font-weight="700">{t(stage["number"])}</text>',
        ])
        for line_index, value in enumerate(textwrap.wrap(stage["label"], width=18)):
            parts.append(f'<text x="{x + 28}" y="{328 + line_index * 29}" fill="{color}" font-family="Arial, sans-serif" font-size="22" font-weight="700">{t(value)}</text>')
        detail_y = 390 if len(textwrap.wrap(stage["label"], width=18)) > 1 else 375
        for line_index, value in enumerate(textwrap.wrap(stage["detail"], width=28)):
            parts.append(f'<text x="{x + 28}" y="{detail_y + line_index * 27}" fill="{INK}" font-family="Arial, sans-serif" font-size="20">{t(value)}</text>')
        if stage.get("note"):
            parts.append(f'<text x="{x + 28}" y="438" fill="{MUTED}" font-family="Arial, sans-serif" font-size="20">{t(stage["note"])}</text>')
        if index < len(xs) - 1:
            parts.append(f'<path d="M{x + 318} 345 H{x + 353}" stroke="#CBD5E1" stroke-width="6" marker-end="url(#arrow)"/>')
    parts.extend([
        '<path d="M1320 468 V512" stroke="#F7D73A" stroke-width="5" marker-end="url(#arrow)"/>',
        '<rect x="1165" y="528" width="310" height="76" rx="38" fill="#151A13" stroke="#F7D73A" stroke-width="3"/>',
        f'<text x="1320" y="576" text-anchor="middle" fill="#F7D73A" font-family="Arial, sans-serif" font-size="22" font-weight="700">{t(render["output"])}</text>',
        '<line x1="70" y1="652" x2="1530" y2="652" stroke="#334155" stroke-width="2"/>',
        '<text x="70" y="700" fill="#F7D73A" font-family="Arial, sans-serif" font-size="20" font-weight="700" letter-spacing="2">CURRENT BOUNDARY</text>',
        f'<text x="390" y="700" fill="{INK}" font-family="Arial, sans-serif" font-size="22">{t(render["boundary"])}</text>',
        '</svg>',
    ])
    return "\n".join(parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    brief_path = FIGURES / f"{FIGURE_ID}.figure.json"
    render_path = FIGURES / f"{FIGURE_ID}.render.json"
    output = FIGURES / f"{FIGURE_ID}.svg"
    brief_bytes = brief_path.read_text(encoding="utf-8").encode("utf-8")
    render_bytes = render_path.read_text(encoding="utf-8").encode("utf-8")
    built = svg(json.loads(brief_bytes), json.loads(render_bytes), hashlib.sha256(brief_bytes).hexdigest(), hashlib.sha256(render_bytes).hexdigest())
    if args.check:
        if not output.exists() or output.read_text(encoding="utf-8") != built:
            raise SystemExit("canonical lifecycle SVG is stale; run scripts/build_figure.py")
    else:
        output.write_text(built, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
