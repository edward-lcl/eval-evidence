#!/usr/bin/env python3
"""Build the README figures in figures/readme/ (hero, one-zero-three-readings, findings).

They reuse the visual language of the five verified figures in figures/: the same dark
canvas, Arial, teaching palette, numbered circles, outlined cards and boundary footer. They are
README illustrations, not part of the verified figure set, so they live in their own folder.
SVG is canonical (selectable text); 2x PNG renditions are produced when rsvg-convert is present.

    python3 scripts/build_readme_figures.py
"""
from __future__ import annotations

import shutil
import subprocess
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "figures" / "readme"

BG, CARD, EDGE = "#090E16", "#111827", "#334155"
INK, MUTED, ARROW = "#F8FAFC", "#A7B0C0", "#CBD5E1"
TEAL, VIOLET, AMBER, CORAL, GREY = "#39D0C3", "#B18CFF", "#F7D73A", "#FF7A59", "#CBD5E1"
SANS, MONO = "Arial, sans-serif", "Menlo, Consolas, 'DejaVu Sans Mono', monospace"


def t(x, y, s, size=22, fill=INK, weight=400, anchor="start", family=SANS, spacing=None):
    ls = f' letter-spacing="{spacing}"' if spacing else ""
    return (f'<text x="{x}" y="{y}" fill="{fill}" font-family="{family}" font-size="{size}" '
            f'font-weight="{weight}" text-anchor="{anchor}"{ls}>{escape(s)}</text>')


def card(x, y, w, h, stroke=EDGE, fill=CARD, r=20, sw=2):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{r}" fill="{fill}" stroke="{stroke}" stroke-width="{sw}"/>'


def num(cx, cy, n, color):
    return f'<circle cx="{cx}" cy="{cy}" r="22" fill="{color}"/>' + t(cx, cy + 8, str(n), 22, BG, 700, "middle")


def pill(x, y, w, label, color, h=46):
    return (f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{h // 2}" fill="{BG}" stroke="{color}" stroke-width="3"/>'
            + t(x + w / 2, y + h / 2 + 8, label, 21, color, 700, "middle", MONO))


def arrow(x1, y1, x2, y2):
    return f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{ARROW}" stroke-width="4" marker-end="url(#arrow)"/>'


def rule(y, x1=70, x2=1530):
    return f'<line x1="{x1}" y1="{y}" x2="{x2}" y2="{y}" stroke="{EDGE}" stroke-width="2"/>'


def svg(w, h, title, desc, body):
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by scripts/build_readme_figures.py -->
<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}" role="img" aria-labelledby="t d">
<title id="t">{escape(title)}</title>
<desc id="d">{escape(desc)}</desc>
<defs><marker id="arrow" markerWidth="11" markerHeight="11" refX="9" refY="5" orient="auto"><path d="M0 0 L0 10 L10 5 Z" fill="{ARROW}"/></marker></defs>
<rect width="{w}" height="{h}" rx="28" fill="{BG}"/>
{body}
</svg>
"""


def hero():
    b = [t(70, 92, "EVAL EVIDENCE", 22, TEAL, 700, spacing="3"),
         t(70, 172, "A SCORE IS NOT", 66, INK, 700),
         t(70, 246, "A DIAGNOSIS", 66, INK, 700),
         t(70, 306, "Record what each number rests on.", 26, MUTED),
         t(70, 344, "Show missing evidence as missing.", 26, MUTED),
         rule(402, 70, 700),
         t(70, 450, "OFFLINE", 20, AMBER, 700, spacing="2"),
         t(186, 450, "runs no models · uploads nothing · never guesses", 20, INK)]
    b += [card(780, 150, 230, 230, CORAL),
          t(895, 200, "SCORE", 20, CORAL, 700, "middle", spacing="2"),
          t(895, 298, "0.58", 72, INK, 700, "middle"),
          t(895, 342, "a reported score", 18, MUTED, 400, "middle"),
          arrow(1018, 265, 1066, 265),
          card(1080, 110, 450, 380, VIOLET),
          t(1110, 158, "evidence.json", 24, VIOLET, 700, family=MONO)]
    for i, (field, state, color) in enumerate([("max_turns", "observed", TEAL), ("model_id", "unavailable", GREY),
                                                ("item_validity", "unavailable", GREY)]):
        y = 190 + i * 74
        b += [t(1110, y + 30, field, 22, INK, 400, family=MONO), pill(1320, y, 180, state, color)]
    b += [rule(420, 1110, 1500),
          t(1110, 460, "sha256 sealed", 20, AMBER, 700, family=MONO),
          t(1500, 460, "verify → valid", 20, AMBER, 700, "end", MONO)]
    return svg(1600, 540, "A score is not a diagnosis",
               "Eval Evidence: a score is not a diagnosis. Record what each number rests on; show missing evidence as missing. "
               "A reported score of 0.58 flows into an evidence.json record whose fields say how they are known: max_turns observed, "
               "model_id unavailable, item_validity unavailable. The record is sealed with sha256 and verify reports valid. "
               "Offline: runs no models, uploads nothing, never guesses.", "\n".join(b))


def readings():
    b = [t(70, 80, "ONE ZERO, THREE READINGS", 44, INK, 700),
         t(70, 122, "A benchmark task that no agent ever passed", 22, MUTED),
         card(70, 175, 330, 420, CORAL),
         t(235, 380, "0", 170, INK, 700, "middle"),
         t(235, 448, "PASSES", 26, CORAL, 700, "middle", spacing="4"),
         t(235, 500, "all the leaderboard", 20, MUTED, 400, "middle"),
         t(235, 528, "can show", 20, MUTED, 400, "middle")]
    for i, (c, head, line) in enumerate([(TEAL, "A REAL LIMIT", "task and grader verified: the zero is about the agents"),
                                         (CORAL, "A BROKEN MEASUREMENT", "faulty reference or grader: the zero says nothing about ability"),
                                         (GREY, "THE RECORD CANNOT TELL", "a gap, not an error: kept as unavailable")]):
        y = 175 + i * 155
        b += [arrow(410, 385, 516, y + 62), card(530, y, 1000, 125, c),
              num(584, y + 62, i + 1, c), t(630, y + 52, head, 25, c, 700), t(630, y + 90, line, 22, INK)]
    b += [rule(645), t(70, 692, "CURRENT BOUNDARY", 20, AMBER, 700, spacing="2"),
          t(400, 692, "records the evidence for each reading · does not decide which one is true", 22, INK)]
    return svg(1600, 735, "One zero, three readings",
               "A task no agent ever passed shows 0 passes, all the leaderboard can show. Three readings: 1, a real limit, if task and grader "
               "are verified the zero is about the agents; 2, a broken measurement, a faulty reference or grader means the zero says nothing "
               "about ability; 3, the record cannot tell, a gap rather than an error, kept as unavailable. Current boundary: Eval Evidence "
               "records the evidence for each reading and does not decide which one is true.", "\n".join(b))


def findings():
    b = [t(70, 80, "WHAT RELEASED ARTIFACTS SHOWED", 44, INK, 700),
         t(70, 122, "Released AI-evaluation artifacts, checked link by link · AI review, not human expert validation", 21, MUTED)]
    gap = 28
    w = (1460 - 3 * gap) // 4
    for i, (c, big, l1, l2, small) in enumerate([(TEAL, "142 / 142", "leaderboard scores", "re-derive", "Terminal-Bench 2.0"),
                                                 (AMBER, "72 / 142", "rows do not count the", "nominal 445 trials", "retry history not recorded"),
                                                 (VIOLET, "95 / 96", "random-cohort papers", "source-reviewed", "coverage, not reproduction"),
                                                 (CORAL, "15 vs 16", "of 18 issues: our audit", "vs a plain checklist", "no detection advantage")]):
        x = 70 + i * (w + gap)
        b += [card(x, 175, w, 290, c), num(x + 44, 222, i + 1, c), t(x + 30, 318, big, 54, INK, 700),
              t(x + 30, 362, l1, 22, INK), t(x + 30, 392, l2, 22, INK), t(x + 30, 440, small, 19, c, 700)]
    b += [rule(515), t(70, 561, "IN THE CASES EXAMINED", 20, AMBER, 700, spacing="2"),
          t(440, 561, "numbers re-derived · the evidence for what they mean often could not be checked", 22, INK)]
    return svg(1600, 605, "What released artifacts showed",
               "Four findings. 1: 142 of 142 Terminal-Bench 2.0 leaderboard scores re-derive. 2: 72 of 142 rows do not count the nominal "
               "445 trials; retry history is not recorded. 3: 95 of 96 random-cohort papers were source-reviewed; coverage, not reproduction. "
               "4: our claim-level audit found 15 and a plain checklist 16 of 18 issues; no detection advantage. In the cases examined, numbers "
               "re-derived while the evidence for what they mean often could not be checked. AI review, not human expert validation.", "\n".join(b))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    figs = {"eval-evidence-readme-hero": hero(), "eval-evidence-readme-three-readings": readings(), "eval-evidence-readme-findings": findings()}
    for name, s in figs.items():
        (OUT / f"{name}.svg").write_text(s, encoding="utf-8")
        if shutil.which("rsvg-convert"):
            width = int(s.split('width="', 2)[1].split('"')[0])
            subprocess.run(["rsvg-convert", "--width", str(width * 2), "--output", str(OUT / f"{name}.png"), str(OUT / f"{name}.svg")], check=True)
    print("built", ", ".join(figs))


if __name__ == "__main__":
    main()
